"""
Regenerate the trading universe.

The signals are traded on Toobit, but GitHub's runners cannot reach Binance, so
candles come from OKX. This script finds the coins that exist on both, ranks them
by Toobit turnover, and prints a ready-to-paste list for okx.UNIVERSE.

    python tools/build_universe.py
"""

from __future__ import annotations

import json
import os
import sys
import urllib.request

TOOBIT_INFO = "https://api.toobit.com/api/v1/exchangeInfo"
TOOBIT_TICKERS = "https://api.toobit.com/quote/v1/ticker/24hr"
OKX_INSTRUMENTS = "https://www.okx.com/api/v5/public/instruments?instType=SWAP"

STABLECOINS = {"USDC", "USDT", "DAI", "FDUSD", "TUSD", "BUSD", "USDD", "PYUSD", "USDE"}
NON_CRYPTO = {
    "SOXL", "SOXS", "SNDK", "MU", "KORU", "SKHYNIX", "SKHY", "SNXX", "SPCX",
    "GOOGL", "AAPL", "TSLA", "NVDA", "MSFT", "AMZN", "META", "NFLX", "AMD",
    "INTC", "COIN", "MSTR", "PLTR", "CRCL", "BABA", "TSM", "ORCL", "IBM",
    "XAU", "XAG", "XPT", "XPD", "CL", "BZ", "NG", "COPPER",
    "QQQ", "SPY", "VOO", "IWM", "DIA", "TQQQ", "SQQQ", "ARKK",
    "GLD", "SLV", "USO", "UNG", "EEM", "FXI",
}


def get(url: str):
    request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.loads(response.read().decode("utf-8"))


def main() -> int:
    limit = int(sys.argv[1]) if len(sys.argv) > 1 else 20

    info = get(TOOBIT_INFO)
    toobit = {
        item["baseAsset"]
        for item in info["symbols"]
        if item.get("quoteAsset") == "USDT" and item.get("status") == "TRADING"
    }

    tickers = get(TOOBIT_TICKERS)
    turnover: dict[str, float] = {}
    for ticker in tickers:
        symbol = ticker.get("s") or ticker.get("si") or ""
        if not symbol.endswith("USDT"):
            continue
        try:
            turnover[symbol[:-4]] = float(ticker.get("qv") or 0)
        except (TypeError, ValueError):
            continue

    okx = get(OKX_INSTRUMENTS)
    okx_bases = {
        item["instId"].split("-")[0]
        for item in okx["data"]
        if item.get("instId", "").endswith("-USDT-SWAP") and item.get("state") == "live"
    }

    both = sorted(
        (
            base
            for base in toobit
            if base in okx_bases and base not in STABLECOINS and base not in NON_CRYPTO
        ),
        key=lambda base: turnover.get(base, 0),
        reverse=True,
    )[:limit]

    print(f"toobit USDT: {len(toobit)} | okx swaps: {len(okx_bases)} | usable: {len(both)}\n")
    for index, base in enumerate(both, 1):
        print(f"{index:>3}. {base:<8} {turnover.get(base, 0) / 1e6:>9,.2f}M")

    target = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "universe.py")
    with open(target, "w", encoding="utf-8") as handle:
        handle.write('"""\n')
        handle.write("Trading universe, generated by tools/build_universe.py.\n")
        handle.write("Every entry is listed on Toobit (where the trades happen) and has an\n")
        handle.write("OKX perpetual (where the candles come from, since GitHub's runners\n")
        handle.write("cannot reach Binance). Do not edit by hand - regenerate instead.\n")
        handle.write('"""\n\n')
        handle.write("UNIVERSE = [\n")
        line = "   "
        for base in both:
            token = f' "{base}",'
            if len(line) + len(token) > 92:
                handle.write(line + "\n")
                line = "   "
            line += token
        handle.write(line + "\n")
        handle.write("]\n")

    print(f"\nwritten to {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
